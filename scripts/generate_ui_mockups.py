def esc(value: object) -> str:
    return html.escape(str(value), quote=True)


class Canvas:
    def __init__(self, width: int, height: int, logical_width: int, logical_height: int, title: str, filename: str):
        self.w = logical_width
        self.h = logical_height
        self.parts = [
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {logical_width} {logical_height}" role="img" aria-labelledby="title desc">',
            f'<title id="title">{esc(title)}</title>',
            '<desc id="desc">Meridian UI 1.0 specification mockup. Visual contract only; unavailable domain controls do not imply implementation.</desc>',
            f'<!-- Generated by scripts/generate_ui_mockups.py from docs/production/ui-mockups/mockups.json; schema meridian.ui-mockup-set/v1; generator 1.0.0; output {esc(filename)}; regenerate: python3 scripts/generate_ui_mockups.py -->',
            '<defs>',
            '<linearGradient id="viewport" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#121515"/><stop offset="1" stop-color="#090b0b"/></linearGradient>',
            '<linearGradient id="warm" x1="0" y1="0" x2="1" y2="0"><stop offset="0" stop-color="#8d8961" stop-opacity=".22"/><stop offset="1" stop-color="#c0964e" stop-opacity=".06"/></linearGradient>',
            '<filter id="shadow" x="-20%" y="-20%" width="140%" height="140%"><feDropShadow dx="0" dy="8" stdDeviation="12" flood-color="#090b0b" flood-opacity=".75"/></filter>',
            '</defs>',
            f'<rect width="{logical_width}" height="{logical_height}" fill="{COLOR["background"]}"/>',
            '<g font-family="Mona Sans, system-ui, sans-serif" font-size="13" fill="#e3e1d8">',
        ]

    def rect(self, x, y, w, h, *, fill="surface", stroke="border", r=6, opacity=1, sw=1):
        self.parts.append(
            f'<rect x="{x}" y="{y}" width="{max(0, w)}" height="{max(0, h)}" rx="{r}" fill="{COLOR.get(fill, fill)}" fill-opacity="{opacity}" stroke="{COLOR.get(stroke, stroke)}" stroke-width="{sw}"/>'
        )

    def line(self, x1, y1, x2, y2, *, stroke="border", sw=1, opacity=1):
        self.parts.append(f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{COLOR.get(stroke, stroke)}" stroke-width="{sw}" stroke-opacity="{opacity}"/>')

    def text(self, x, y, value, *, fill="primary", size=13, weight=450, anchor="start", mono=False, opacity=1):
        family = ' font-family="JetBrains Mono, monospace"' if mono else ""
        self.parts.append(f'<text x="{x}" y="{y}" fill="{COLOR.get(fill, fill)}" font-size="{size}" font-weight="{weight}" text-anchor="{anchor}" opacity="{opacity}"{family}>{esc(value)}</text>')

    def circle(self, x, y, radius, *, fill="muted", opacity=1):
        self.parts.append(f'<circle cx="{x}" cy="{y}" r="{radius}" fill="{COLOR.get(fill, fill)}" opacity="{opacity}"/>')

    def path(self, data, *, stroke="secondary", fill="none", sw=1.5, opacity=1):
        self.parts.append(f'<path d="{data}" fill="{COLOR.get(fill, fill)}" stroke="{COLOR.get(stroke, stroke)}" stroke-width="{sw}" stroke-linecap="round" stroke-linejoin="round" opacity="{opacity}"/>')

    def close(self):
        self.parts.extend(["</g>", "</svg>"])
        return "\n".join(self.parts) + "\n"


def header(c: Canvas, active: str, narrow: bool = False):
    c.rect(0, 0, c.w, 44, r=0)
    for index, color in enumerate(("destructive", "warning", "positive")):
        c.circle(18 + index * 18, 22, 5, fill=color, opacity=.9)
    c.text(82, 27, "Meridian", weight=650)
    c.text(144, 27, "·  Creator Alpha", fill="secondary")
    if narrow:
        utilities = [(c.w - 254, "Play"), (c.w - 194, "Build"), (c.w - 126, "Search"), (c.w - 54, "•••")]
    else:
        utilities = [(c.w - 330, "▶  Play"), (c.w - 242, "Build"), (c.w - 166, "Search"), (c.w - 82, "Settings")]
    for x, label in utilities:
        if "Play" in label:
            c.rect(x - 12, 8, 72, 28, fill="positive", stroke="positive", r=6, opacity=.22)
        c.text(x, 27, label, fill="primary" if "Play" in label else "secondary", weight=600 if "Play" in label else 450)

    c.rect(0, 44, c.w, 36, r=0)
    available = c.w - 40
    positions = []
    x = 20
    for name in WORKSPACES:
        width = max(48, 18 + len(name) * 7)
        if x + width > available:
            break
        positions.append((x, width, name))
        x += width + 4
    for x, width, name in positions:
        selected = name == active
        if selected:
            c.rect(x, 49, width, 26, fill="surface", stroke="warning", r=6, opacity=1)
            c.line(x + 8, 74, x + width - 8, 74, stroke="warning", sw=2)
        c.text(x + width / 2, 68, name, fill="primary" if selected else "secondary", size=12, weight=600 if selected else 450, anchor="middle")
    if len(positions) < len(WORKSPACES):
        c.text(c.w - 22, 68, "•••", fill="secondary", anchor="end")


