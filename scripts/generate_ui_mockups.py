def generate(entry, version):
    width, height = entry["width"], entry["height"]
    logical_width = entry.get("logical_width", width)
    logical_height = entry.get("logical_height", height)
    c = Canvas(width, height, logical_width, logical_height, entry["title"], entry["file"])
    workspace, variant = entry["workspace"], entry["variant"]
    if workspace == "Hub":
        draw_hub(c)
    elif workspace == "World":
        draw_world(c, variant)
    elif workspace == "Code":
        draw_code(c, variant)
    elif workspace == "Modeler":
        draw_modeler(c)
    elif workspace == "UI":
        draw_ui_authoring(c)
    elif workspace in ("Materials", "Alluvium"):
        draw_materials_or_alluvium(c, workspace)
    elif workspace == "Build":
        draw_build(c)
    elif workspace == "Profile":
        draw_profile(c)
    elif workspace == "Settings":
        draw_settings(c)
    elif workspace == "Recovery":
        draw_recovery(c)
    else:
        raise ValueError(f"unknown workspace {workspace}")
    if variant == "high-contrast":
        c.parts.insert(-1, f'<rect x="2" y="2" width="{c.w-4}" height="{c.h-4}" rx="10" fill="none" stroke="{COLOR["primary"]}" stroke-width="2" pointer-events="none"/>')
    return c.close()


def main():
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    if manifest.get("schema") != "meridian.ui-mockup-set/v1":
        raise SystemExit("unsupported mockup manifest schema")
    OUT.mkdir(parents=True, exist_ok=True)
    expected = {entry["file"] for entry in manifest["outputs"]}
    for stale in OUT.glob("*.svg"):
        if stale.name not in expected:
            stale.unlink()
    for entry in manifest["outputs"]:
        target = OUT / entry["file"]
        target.write_text(generate(entry, manifest["generator_version"]), encoding="utf-8")
    print(f"generated {len(expected)} Meridian UI mockups in {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
